// `swiss-function guide`: write the library's usage guide into a host project,
// for the coding agents that build its UI. The guide itself is built from
// AGENTS.md at package build time (scripts/guide/build.mjs) and ships in
// dist/guide/ with the API reference and AESTHETICS.md; this writes it to the
// host with its links pointing at those files in the installed package.

import { existsSync, realpathSync } from "node:fs";
import { lstat, mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve, sep } from "node:path";

export const PACKAGE = "@tarassov-ch/swiss-function";
export const DEFAULT_OUT = "SWISS-FUNCTION.md";

/** The first line of a file this command wrote: a later run may overwrite
 *  such a file, and no other without `--force`. */
export const MARK = "<!-- Generated by `npx swiss-function guide`";

export const HELP = `Usage: npx swiss-function guide [options]

Write the guide to using ${PACKAGE} into this project, for the coding
agents that build its UI (Claude Code, Cursor, Codex, ...). Run it again
after upgrading the library.

Options:
  --out <file>  Where to write it. Default ${DEFAULT_OUT}.
  --link        Reference it from AGENTS.md and CLAUDE.md in this directory.
  --force       Overwrite a file this command did not write.
  --stdout      Print the guide instead of writing it.
  -h, --help    Show this help.
`;

/** Parse `guide` and its options. */
export function parseArgs(argv) {
  /** @type {{ command: string | undefined, out: string, link: boolean, force: boolean, stdout: boolean, error?: string }} */
  const args = { command: argv[0], out: DEFAULT_OUT, link: false, force: false, stdout: false };
  for (let i = 1; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--out") {
      const value = argv[++i];
      if (!value) return { ...args, error: "--out needs a file name" };
      args.out = value;
    } else if (a === "--link") args.link = true;
    else if (a === "--force") args.force = true;
    else if (a === "--stdout") args.stdout = true;
    else if (a === "-h" || a === "--help") args.command = "help";
    else return { ...args, error: `unknown option ${a}` };
  }
  return args;
}

/** Links as relative paths from a file's directory, with forward slashes. */
function linkPath(fromDir, to) {
  const rel = relative(fromDir, to).split(sep).join("/");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

/** The guide as the host gets it: the generated mark and the version on top,
 *  the links pointing at the shipped files from where the guide is written. */
export function renderForHost(guide, { version, outDir, guideDir }) {
  const to = linkPath(outDir, guideDir);
  const body = guide
    .replaceAll("](./API.md", `](${to}/API.md`)
    .replaceAll("](./AESTHETICS.md", `](${to}/AESTHETICS.md`);
  return `${MARK} from ${PACKAGE} ${version}. Run it again after upgrading; edits here are overwritten. -->\n\n${body}`;
}

/** Where the package's guide is, seen from the host: the installed package
 *  as Node resolves it from `cwd` (a hoisted or linked install included). When
 *  it is not installed there (`npx` fetched it), the links point where it
 *  will be once it is, and `installed` is false. */
export function locateGuide(cwd) {
  try {
    const req = createRequire(join(cwd, "noop.js"));
    const pkgJson = req.resolve(`${PACKAGE}/package.json`);
    return { guideDir: join(dirname(pkgJson), "dist", "guide"), installed: true };
  } catch {
    return {
      guideDir: join(cwd, "node_modules", ...PACKAGE.split("/"), "dist", "guide"),
      installed: false,
    };
  }
}

/** Add a reference to the guide to the host's agent instructions, once.
 *  AGENTS.md gets a sentence with a link; a CLAUDE.md of its own gets an
 *  `@` import, which Claude Code loads with it. A CLAUDE.md that is a link to
 *  AGENTS.md is the same file and is changed once. Returns what it did, a line
 *  per file. */
export async function linkGuide(cwd, outPath) {
  const done = [];
  const seen = new Set();
  for (const name of ["AGENTS.md", "CLAUDE.md"]) {
    const file = join(cwd, name);
    if (!existsSync(file)) continue;
    const real = realpathSync(file);
    if (seen.has(real)) continue;
    seen.add(real);
    const rel = linkPath(dirname(real), outPath).replace(/^\.\//, "");
    const text = await readFile(real, "utf8");
    if (text.includes(rel)) {
      done.push(`${name} already refers to ${rel}`);
      continue;
    }
    const isClaude = name === "CLAUDE.md" && !(await lstat(file)).isSymbolicLink();
    const line = isClaude
      ? `This project builds its UI with \`${PACKAGE}\`; read its guide first: @${rel}`
      : `This project builds its UI with \`${PACKAGE}\`. Read [${rel}](${rel}) before writing UI code.`;
    await writeFile(real, `${text.replace(/\s*$/, "")}\n\n${line}\n`);
    done.push(`${name}: added a reference to ${rel}`);
  }
  return done;
}

/** Run the command. `io` carries the directories and the output streams, so
 *  tests can run it in a temporary project. Returns the exit code. */
export async function run(argv, io) {
  const { cwd, pkgDir, out, err } = io;
  const args = parseArgs(argv);
  if (args.error) {
    err(`swiss-function: ${args.error}\n\n${HELP}`);
    return 2;
  }
  if (!args.command || args.command === "help") {
    out(HELP);
    return 0;
  }
  if (args.command !== "guide") {
    err(`swiss-function: unknown command ${args.command}\n\n${HELP}`);
    return 2;
  }

  const source = join(pkgDir, "dist", "guide", "GUIDE.md");
  if (!existsSync(source)) {
    err(
      `swiss-function: the guide is missing from ${pkgDir} (dist/guide/GUIDE.md); is the package built?\n`,
    );
    return 1;
  }
  const pkg = JSON.parse(await readFile(join(pkgDir, "package.json"), "utf8"));
  const outPath = resolve(cwd, args.out);
  const { guideDir, installed } = locateGuide(cwd);
  const text = renderForHost(await readFile(source, "utf8"), {
    version: pkg.version,
    outDir: dirname(outPath),
    guideDir,
  });

  if (args.stdout) {
    out(text);
    return 0;
  }

  if (existsSync(outPath) && !args.force) {
    const current = await readFile(outPath, "utf8");
    if (!current.startsWith(MARK)) {
      err(
        `swiss-function: ${args.out} exists and was not written by this command; pass --force to overwrite it, or --out to write elsewhere.\n`,
      );
      return 1;
    }
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  out(`Wrote ${args.out} (${PACKAGE} ${pkg.version}).\n`);
  if (!installed) {
    out(
      `Its links point into node_modules/${PACKAGE}; install the package here for them to resolve.\n`,
    );
  }

  if (args.link) {
    const done = await linkGuide(cwd, outPath);
    if (done.length === 0) {
      out(`No AGENTS.md or CLAUDE.md here: point your agent's instructions at ${args.out}.\n`);
    }
    for (const line of done) out(`${line}\n`);
  } else {
    out(
      `Point your agent's instructions at it (or run again with --link to add a line to AGENTS.md and CLAUDE.md).\n`,
    );
  }
  return 0;
}
